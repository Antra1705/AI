// ml_model.h - 8-bit neural-network road classifier with uncertainty (#6, #8).
//
// Model: an ensemble of small MLPs (16 -> 16 -> 16 -> 4, ReLU), each trained
// with quantization-aware training so it runs in int8 on the ESP32:
//   - weights int8, per-tensor symmetric scale
//   - layer inputs quantized to int8 with a fixed, calibrated scale
//   - int32 accumulation, one float rescale per output
// About 600 bytes of weights per member; 5 members take ~3 kB of flash and
// well under 1 ms per prediction.
//
// Uncertainty (#8), two complementary estimates:
//  1. Model uncertainty - approximate Bayesian model averaging with a deep ensemble:
//       p           = mean over members of softmax(logits / T)   (T fitted on validation data)
//       entropy     = H(p)                          total uncertainty
//       mutual_info = H(p) - mean_m H(p_m)          disagreement between members
//  2. Data novelty - class-conditional Gaussian model of the training features
//     (shared covariance): novelty = min over classes of the squared Mahalanobis
//     distance. High when the input looks like none of the trained surfaces.
// A prediction is 'uncertain' (safety fallback) when confidence is low, members
// disagree, or the input is novel. The response curve also uses these values
// continuously.
//
// The weights live in model_data.cpp, generated by host/train (do not hand-edit).
#pragma once
#include <stdint.h>

#include "ml_features.h"

enum { ML_CLASSES = 4, ML_LAYERS = 3, ML_MAX_WIDTH = 32 };

// Round half away from zero, clamp to [-127, 127]. The trainer uses this same function.
int8_t quantizeS8(float x, float scale);

struct QLayer {
  int in, out;
  const int8_t* w;   // out x in, row-major
  const int32_t* b;  // bias in units of in_scale * w_scale
  float in_scale;    // input quantization scale
  float w_scale;     // weight scale
};

struct QNet {
  QLayer layer[ML_LAYERS];
};

struct MlEnsemble {
  int members;           // 0 = no model available
  const QNet* nets;
  const float* feat_mean;
  const float* feat_std;
  float temperature;
  float mi_threshold;    // above this: members disagree -> fallback
  float conf_threshold;  // below this: not confident -> fallback
  const float* class_means;  // ML_CLASSES x ML_FEATURE_COUNT, standardized features
  const float* inv_cov;      // ML_FEATURE_COUNT x ML_FEATURE_COUNT shared inverse covariance
  float novelty_threshold;   // above this: input unlike any training surface -> fallback
  const char* info;          // training summary
};

const MlEnsemble& deployedModel();

// One network on standardized features. Integer arithmetic as on the ESP32.
void qnetForward(const QNet& net, const float x[], float logits[ML_CLASSES]);

// Squared Mahalanobis distance of standardized features to the nearest class mean.
float mlNovelty(const MlEnsemble& m, const float x_standardized[ML_FEATURE_COUNT]);

struct MlPrediction {
  bool valid;
  float p[ML_CLASSES];  // calibrated class probabilities, index = Surface
  int top;
  float confidence;     // max p
  float entropy;        // nats
  float mutual_info;    // nats
  float novelty;        // squared Mahalanobis distance to the nearest class
  bool uncertain;       // any of the three signals past its threshold
};

MlPrediction mlPredict(const MlEnsemble& m, const float features[ML_FEATURE_COUNT]);
