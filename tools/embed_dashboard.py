#!/usr/bin/env python3
"""Copy host/dashboard/index.html into the ESP32 firmware as a C++ string.

    python3 tools/embed_dashboard.py

Run after editing index.html; `make -C host test` fails until the copy matches.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "host", "dashboard", "index.html")
DST = os.path.join(ROOT, "adaptive_suspension", "src", "esp32", "dashboard_html.h")
DELIM = "DASHBOARD"

html = open(SRC, encoding="utf-8").read()
assert ")" + DELIM + '"' not in html, "index.html contains the raw-string delimiter"
with open(DST, "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/embed_dashboard.py from host/dashboard/index.html - do not edit.\n")
    f.write("// The cart serves this page itself over WiFi (web_dashboard.cpp).\n")
    f.write("#pragma once\n\n")
    f.write('static const char DASHBOARD_HTML[] = R"%s(%s)%s";\n' % (DELIM, html, DELIM))
print("wrote %s (%d bytes of HTML)" % (os.path.relpath(DST, ROOT), len(html.encode("utf-8"))))
