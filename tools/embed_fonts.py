#!/usr/bin/env python3
"""Embed the dashboard's fonts into host/dashboard/index.html (works offline, also on the cart).

    python3 tools/embed_fonts.py                         re-embed host/dashboard/fonts/*.woff
    .venv/bin/python tools/embed_fonts.py --from DIR     subset Barlow TTFs from DIR first (needs fontTools)

Fonts: Barlow and Barlow Condensed, (c) 2017 The Barlow Project Authors, SIL Open Font License 1.1
(host/dashboard/fonts/OFL.txt). Then run tools/embed_dashboard.py to update the firmware copy.
"""
import argparse
import base64
import os
import re
import shutil

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONT_DIR = os.path.join(ROOT, "host", "dashboard", "fonts")
HTML = os.path.join(ROOT, "host", "dashboard", "index.html")

# (file stem, CSS family, weight)
FACES = [
    ("BarlowCondensed-Medium", "Barlow Condensed", 500),
    ("BarlowCondensed-SemiBold", "Barlow Condensed", 600),
    ("Barlow-Regular", "Barlow", 400),
]
# Basic Latin plus the few symbols the page uses.
UNICODES = list(range(0x20, 0x7F)) + [0xA0, 0xB0, 0xB7, 0xD7, 0x2002, 0x2013, 0x2014, 0x2019, 0x201C, 0x201D,
                                      0x2026, 0x2212]


def subset(src_dir):
    from fontTools import subset as fts
    from fontTools.ttLib import TTFont

    os.makedirs(FONT_DIR, exist_ok=True)
    for stem, _, _ in FACES:
        font = TTFont(os.path.join(src_dir, stem + ".ttf"))
        opts = fts.Options()
        opts.layout_features = ["kern", "liga", "locl", "tnum", "pnum"]
        opts.hinting = False
        opts.flavor = "woff"
        sub = fts.Subsetter(opts)
        sub.populate(unicodes=UNICODES)
        sub.subset(font)
        font.flavor = "woff"
        out = os.path.join(FONT_DIR, stem + ".woff")
        font.save(out)
        print("subset %-26s %6d bytes" % (stem, os.path.getsize(out)))
    lic = os.path.join(src_dir, "OFL.txt")
    if os.path.exists(lic):
        shutil.copy(lic, os.path.join(FONT_DIR, "OFL.txt"))


def embed():
    css = ["/* FONTS:BEGIN (generated by tools/embed_fonts.py, do not edit by hand). Barlow and Barlow Condensed,",
           "   (c) 2017 The Barlow Project Authors, SIL Open Font License 1.1: host/dashboard/fonts/OFL.txt */"]
    for stem, family, weight in FACES:
        data = open(os.path.join(FONT_DIR, stem + ".woff"), "rb").read()
        css.append('@font-face{font-family:"%s";font-weight:%d;font-style:normal;font-display:swap;'
                   'src:url(data:font/woff;base64,%s) format("woff")}' % (family, weight, base64.b64encode(data).decode()))
    css.append("/* FONTS:END */")
    html = open(HTML, encoding="utf-8").read()
    new, n = re.subn(r"/\* FONTS:BEGIN.*?FONTS:END \*/", lambda m: "\n".join(css), html, flags=re.S)
    assert n == 1, "FONTS:BEGIN/END markers not found in index.html"
    open(HTML, "w", encoding="utf-8").write(new)
    print("embedded %d faces into %s (%d bytes)" % (len(FACES), os.path.relpath(HTML, ROOT), len(new.encode())))


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="src", help="directory with the Barlow .ttf files (and OFL.txt) to subset first")
    args = ap.parse_args()
    if args.src:
        subset(args.src)
    embed()
